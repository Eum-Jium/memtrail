"""
unpack_claude_code_jsonl 시스템 주입 필터 테스트 (비대화형, assert 기반).

실행: python test_unpack_filters.py
기대: 전부 통과 시 exit 0, 실패 시 AssertionError 로 exit != 0
"""
import json
import sys
import tempfile
from pathlib import Path

from unpack_claude_code_jsonl import (
    _clean_user_turn,
    _local_time,
    parse_session,
    peek_session_meta,
)

# 2026-08-26 부터 턴에 사용자 발화 시각이 세 번째 원소로 실린다 (렌더는 헤더 줄에
# 붙인다). 기대값을 파일에 박으면 시간대에 묶이므로 같은 변환기로 계산해 둔다.
TS = _local_time("2026-01-15T10:00:00.000Z")

sys.stdout.reconfigure(encoding="utf-8")

NOTIF = (
    "<task-notification>\n<task-id>bxxxxxxxx</task-id>\n"
    "<status>failed</status>\n<summary>Background command failed</summary>\n"
    "</task-notification>"
)
REMINDER = (
    '<system-reminder>\nThe user started your suggested background task '
    'task_00000000 ("Example task").\n</system-reminder>'
)
CAVEAT = (
    "<local-command-caveat>Caveat: The messages below were generated by the "
    "user while running local commands. DO NOT respond to these messages."
    "</local-command-caveat>"
)
STDOUT = "<local-command-stdout>Set model to claude-fable-5[1m]</local-command-stdout>"
MODEL_CMD = (
    "<command-name>/model</command-name>\n"
    "<command-message>model</command-message>\n"
    "<command-args>claude-fable-5[1m]</command-args>"
)
NOTE_CMD = (
    "<command-message>daily-note</command-message>\n"
    "<command-name>/daily-note</command-name>\n"
    "<command-args>오늘 회의 정리해줘</command-args>"
)
COMPACT = (
    "This session is being continued from a previous conversation that ran "
    "out of context. The summary below covers the earlier portion.\n\nSummary:..."
)


# ────────────────────────────────────────────────────────────────────
print("[1/3] _clean_user_turn 단위 케이스")

# 순수 주입 턴 → drop
for c in (NOTIF, REMINDER, CAVEAT, STDOUT, COMPACT,
          NOTIF + "\n" + NOTIF,                      # 알림 두 개 연달아
          "[Request interrupted by user]",
          "[Request interrupted by user for tool use]",
          "<task-notification>\n<task-id>x</task-id>"):  # 닫는 태그 없이 잘림
    assert _clean_user_turn(c) == (None, False), f"drop 실패: {c[:60]!r}"

# 혼합 턴: 선두 블록만 벗기고 실발화 보존 (실측 케이스)
assert _clean_user_turn(REMINDER + "\n주입 필터 작업부터 시작해줘") == \
    ("주입 필터 작업부터 시작해줘", False)
assert _clean_user_turn("[Request interrupted by user]다시 해줘") == ("다시 해줘", False)
assert _clean_user_turn(NOTIF + "\n" + REMINDER + "\n그래서 결과는?") == \
    ("그래서 결과는?", False)

# 본문 중간에 태그를 *인용*한 실발화는 절대 건드리면 안 됨
quoted = "파서에서 `<task-notification>` 으로 시작하는 턴을 걸러줘"
assert _clean_user_turn(quoted) == (quoted, False)
quoted2 = "예: <system-reminder>foo</system-reminder> 같은 게 섞여"
assert _clean_user_turn(quoted2) == (quoted2, False)

# 슬래시 커맨드 복원
assert _clean_user_turn(MODEL_CMD) == ("/model claude-fable-5[1m]", True)
assert _clean_user_turn(NOTE_CMD) == ("/daily-note 오늘 회의 정리해줘", True)

# 평범한 실발화는 그대로
assert _clean_user_turn("안녕, 오늘 뭐 하지?") == ("안녕, 오늘 뭐 하지?", False)
print("   ✅ OK")


# ────────────────────────────────────────────────────────────────────
def _rec_user(content, is_meta=False, ts="2026-01-15T10:00:00.000Z"):
    d = {"type": "user", "timestamp": ts,
         "message": {"role": "user", "content": content}}
    if is_meta:
        d["isMeta"] = True
    return d


def _rec_asst(text, ts="2026-01-15T10:00:05.000Z"):
    return {"type": "assistant", "timestamp": ts,
            "message": {"role": "assistant",
                        "content": [{"type": "text", "text": text}]}}


def _write_jsonl(tmpdir, name, records):
    p = Path(tmpdir) / name
    p.write_text("\n".join(json.dumps(r, ensure_ascii=False) for r in records),
                 encoding="utf-8")
    return p


print("[2/3] parse_session 통합 (턴 페어링)")
with tempfile.TemporaryDirectory() as td:
    records = [
        {"type": "ai-title", "aiTitle": "필터 테스트"},
        _rec_user("데이터 이식 마무리해줘"),
        _rec_asst("잠시 후 최종 정리해 드리겠습니다."),
        _rec_user(NOTIF),                      # 주입 → 어시스턴트 텍스트는 계속 직전 턴에
        _rec_asst("설치가 실패했네요. 원인을 확인합니다."),
        _rec_user(CAVEAT, is_meta=True),       # isMeta 레코드
        _rec_user(MODEL_CMD),                  # /model — 응답 없음 → 페어 drop
        _rec_user(STDOUT),
        _rec_user("이제 요약해줘"),
        _rec_asst("요약입니다."),
    ]
    p = _write_jsonl(td, "s1.jsonl", records)
    parsed = parse_session(p)
    assert parsed is not None
    assert parsed["turns"] == [
        ("데이터 이식 마무리해줘",
         "잠시 후 최종 정리해 드리겠습니다.\n\n설치가 실패했네요. 원인을 확인합니다.", TS),
        ("이제 요약해줘", "요약입니다.", TS),
    ], parsed["turns"]

    # 주입 턴만 있는 세션 → 빈 대화로 취급 (None)
    p2 = _write_jsonl(td, "s2.jsonl", [_rec_user(NOTIF), _rec_asst("혼잣말")])
    assert parse_session(p2) is None
print("   ✅ OK")


