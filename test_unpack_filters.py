print("[3/3] 슬래시 커맨드 첫 발화 복원 (args 가 실발화인 경우)")
with tempfile.TemporaryDirectory() as td:
    records = [
        _rec_user(NOTE_CMD),
        _rec_asst("네, 회의 내용을 정리해 드릴게요."),
    ]
    p = _write_jsonl(td, "s3.jsonl", records)
    meta = peek_session_meta(p)
    # 옛 분류 필드는 2026-08-15 폐지 — 이제 판별 필드가 없고 전부 일반 대화다.
    assert "is_mental_room" not in meta, meta
    # 남는 요구사항: 커맨드 주입을 통째로 버리지 않고 사용자가 실제 친 한 줄로
    # 복원해야 한다. args 가 곧 실발화인 경우가 있어 여기서 잃으면 대화가 잘린다.
    parsed = parse_session(p, meta=meta)
    assert parsed["turns"] == [
        ("/daily-note 오늘 회의 정리해줘", "네, 회의 내용을 정리해 드릴게요.", TS),
    ], parsed["turns"]
print("   ✅ OK")

print("\n모든 테스트 통과 ✅")
